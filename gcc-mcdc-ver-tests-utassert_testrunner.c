 /*=========================================================================*//**
 ** \brief Parse a .gcov file and update the CoverageDB with function, branch,
 **        block, line, call, and condition coverage information
 ** \param [in] filename Path to the .gcov file to be parsed  Must not be NULL
 ** \param [in,out] db Pointer to a CoverageDB structure that will be populated
 **                   with parsed coverage data  Must not be NULL
 ** \details Reads the .gcov file line by line, identifies function boundaries,
 **          counts source lines, blocks, branches, calls, and condition
 **          coverage, and updates the corresponding structures in the database
 **          The parser relies on gcov's textual output format and extracts
 **          numeric identifiers and coverage counts using sscanf and string
 **          matching
 ** \verbatim
 ** Global_reads_writes Reads: file contents  Writes: db->funcs and all
 **         nested coverage fields
 ** Limitations,Assumptions,Notes
 **          - Caller must provide valid filename and db pointers
 **          - Function terminates the program on file open failure
 **          - Parsing depends on gcov's output format and may break if the
 **            format changes
 **          - Only the patterns used by this project are recognized
 ** Algorithm:
 **   Open the .gcov file for reading
 **   If the file cannot be opened:
 **       Print an error and exit
 **   Initialize state: no current function and last_block_id = -1
 **   For each line in the file:
 **       Trim whitespace
 **       Skip empty lines
 **       If inside a function:
 **           Detect numbered source lines and count unique line numbers
 **       If the line begins with "function":
 **           Extract the function name
 **           Retrieve or create the FunctionInfo record
 **           Reset line and block tracking fields
 **           Continue to next line
 **       If no current function:
 **           Continue to next line
 **       Detect "call 0" lines and count calls not taken
 **       Detect block lines containing "-block <n>":
 **           Increment total block count
 **           If execution count is "%%%%%:":
 **               Increment blocks_not_taken
 **       Detect uncovered lines marked "#####:"
 **           Increment uncovered line count
 **       Detect block identifier lines and update last_block_id
 **       Detect condition coverage lines "condition outcomes covered N/M":
 **           Update branch condition coverage and function totals
 **       Detect branch lines:
 **           Add a new branch record
 **           Record taken count and update branches_taken_zero if needed
 **       Detect condition not covered lines:
 **           Add a new condition record and mark missing outcomes
 **   Close the file
 ** History
 **   03/24/2026  Lore/Copilot  Initial code complete & documentation added
 ** \endverbatim
 *//*=========================================================================*/

 static void parse_gcov(const char *filename, CoverageDB *db) {
    FILE *fp = fopen(filename, "r");
    if (!fp) {
        perror(filename);
        exit(1);
    }

    char line[LINEBUF];
    FunctionInfo *current_func = NULL;
    int last_block_id = -1;
    int lineno;
	
    while (fgets(line, sizeof(line), fp)) {
        trim(line);
        if (line[0] == '\0')
            continue;

		/* Count numbered source lines: match "<anything> <number>:" */
		/* First token can be: N:, -:, #####, N*: */
		if (current_func)
		{
			if (sscanf(line, "%*s %d:", &lineno) == 1) {
				/* Only count if strictly greater than last seen */
				if (lineno > current_func->last_line_number) {
					current_func->total_lines++;
					current_func->last_line_number = lineno;
				}
			}
		}

        /* function line */
        if (strncmp(line, "function ", 9) == 0) {
            char fname[256] = {0};
            if (sscanf(line, "function %255s", fname) == 1) {
                current_func = get_function(db, fname);
                last_block_id = -1;
				/* reset line number tracking here */
				current_func->last_line_number = 0;
                current_func->total_lines = 0;
				/* reset block number tracking here */
				current_func->total_blocks = 1;
				current_func->blocks_not_taken = 0;
            }
            continue;
        }

        if (!current_func)
            continue;
		
		/* Count "call 0" at the beginning of a line */
		int num;
		if (sscanf(line, "call %d", &num) == 1 && num == 0) {
			if (strstr(line, "never executed")) {
				current_func->calls_not_taken++;
			}
		}

		/* Count blocks: any line containing "-block <n>" */
		{
			int block_id;

			/* Matches: "117-block 4", "200-block 12", etc. */
			if (sscanf(line, "%*s %*d-block %d", &block_id) == 1) {

				/* Count every block occurrence */
				current_func->total_blocks++;

				/* If the execution count is "%%%%%:" then this block was not taken */
				if (strncmp(line, "%%%%%", 5) == 0)
					current_func->blocks_not_taken++;
			}
		}

        /* uncovered lines: ONLY "#####:" */
        if (strstr(line, "#####:"))
            current_func->uncovered_lines++;

        /* block line */
        if (strstr(line, "-block")) {
            int block_id;
            if (sscanf(line, "%*[^-]-block %d", &block_id) == 1)
                last_block_id = block_id;
            continue;
        }

        /* condition outcomes covered N/M */
        if (strncmp(line, "condition outcomes covered", 26) == 0) {
            int num, den;
			if (sscanf(line, "condition outcomes covered %d/%d", &num, &den) == 2) {
				if (current_func->num_branches > 0) {
					BranchInfo *b = &current_func->branches[current_func->num_branches - 1];
					b->has_cond_coverage = true;
					b->cond_cov_num = num;
					b->cond_cov_den = den;

					current_func->total_conditions       += den;
					current_func->total_conditions_covered += num;
				}
			}
            continue;
        }

        /* branch lines */
        if (strncmp(line, "branch", 6) == 0) {
            int branch_id;
            BranchInfo *b = NULL;

            if (strstr(line, "never executed")) {
                if (sscanf(line, "branch %d never executed", &branch_id) == 1) {
                    b = add_branch(current_func, branch_id, current_func->last_line_number, last_block_id);
                    b->taken_count = 0;
                    current_func->branches_taken_zero++;
                }
            } else {
                int taken;
                if (sscanf(line, "branch %d taken %d", &branch_id, &taken) == 2) {
                    b = add_branch(current_func, branch_id, current_func->last_line_number, last_block_id);
                    b->taken_count = taken;
                    if (taken == 0)
                        current_func->branches_taken_zero++;
                }
            }
            continue;
        }

        /* condition not covered lines */
        if (strncmp(line, "condition", 9) == 0 && strstr(line, "not covered")) {
            int cond_id;
            char missing[128] = {0};

            if (sscanf(line, "condition %d not covered (%127[^)])", &cond_id, missing) == 2) {
                if (current_func->num_branches == 0)
                    continue;

                BranchInfo *b = &current_func->branches[current_func->num_branches - 1];
                ConditionInfo *c = add_condition(b, cond_id);

                if (strstr(missing, "true"))
                    c->true_missing = true;
                if (strstr(missing, "false"))
                    c->false_missing = true;
            }
            continue;
        }
    }

    fclose(fp);
}

