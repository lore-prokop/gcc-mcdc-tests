typedef struct {
    int  cond_id;
    bool true_missing;
    bool false_missing;
} ConditionInfo;

typedef struct {
    int  branch_id;
	int  line_num;
    int  block_id;
    int  taken_count;
    bool has_cond_coverage;
    int  cond_cov_num;
    int  cond_cov_den;
    int  num_conditions;
    int  cap_conditions;
    ConditionInfo *conditions;
} BranchInfo;

typedef struct {
    char name[256];
    int total_lines;
	int last_line_number;   /* last line number seen, for tracking */
	int uncovered_lines;
    int branches_taken_zero;
    int num_branches;
    int cap_branches;
    BranchInfo *branches;
	int total_conditions;
	int total_conditions_covered;
	int calls_not_taken;
	int total_blocks;        /* highest block number + 1 */
	int blocks_not_taken;    /* count of uncovered blocks */
} FunctionInfo;

typedef struct {
    int count;
    int cap;
    FunctionInfo *funcs;
} CoverageDB;

typedef enum {
    LINES_NOT_COVERED,
    BRANCHES_NOT_COVERED,
    CONDITIONS_NOT_COVERED,
	CALLS_NOT_TAKEN,
	TOTAL_LINES,
	BLOCKS_TOTAL,
    BLOCKS_NOT_TAKEN
} QueryType;

