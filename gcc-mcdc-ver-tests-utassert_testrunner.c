/*=========================================================================*//**
 ** \brief Print a human-readable summary of all coverage statistics for every
 **        function stored in the CoverageDB
 ** \param [in] db Pointer to the CoverageDB structure to display  Must not be
 **                NULL
 ** \details Iterates through all functions in the database and prints summary
 **          information including line coverage, block coverage, call coverage,
 **          branch coverage, and condition coverage  Each branch and condition
 **          is printed with its identifiers and coverage status
 ** \verbatim
 ** Global_reads_writes Reads: db->funcs and all nested fields
 **         Writes: stdout
 ** Limitations,Assumptions,Notes
 **          - Output format is intended for human inspection, not machine use
 **          - Caller must provide a valid db pointer
 **          - Printed values reflect previously parsed gcov data
 ** Algorithm:
 **   For each function in the database:
 **       Print the function name
 **       Print total lines, uncovered lines, total blocks, blocks not taken
 **       Print calls not taken
 **       Print branch summary: branches taken zero vs total
 **       Print condition summary: missing vs total
 **       For each branch:
 **           Print branch ID, block ID, and taken count
 **           If condition coverage exists:
 **               Print covered outcomes N/M
 **           For each condition:
 **               Print condition ID and missing true/false flags
 ** History
 **   03/24/2026   Lore/Copilot  Initial code and documentation complete
 ** \endverbatim
 *//*=========================================================================*/
 
 /// \cond
 __attribute__((unused)) 
 /// \endcond
 static void print_summary(const CoverageDB *db)  /* used for debugging, so suppress the warning */
 {
    for (int i = 0; i < db->count; i++) {
        const FunctionInfo *f = &db->funcs[i];
        printf("Function: %s\n", f->name);
		printf("  Total lines: %d\n", f->total_lines);
        printf("  Uncovered lines: %d\n", f->uncovered_lines);
		printf("  Total blocks: %d\n", f->total_blocks);
		printf("  Blocks not taken: %d\n", f->blocks_not_taken);
		printf("  Calls not taken: %d\n", f->calls_not_taken);
        printf("  Total Branches not taken:   %d / %d\n", f->branches_taken_zero, f->num_branches);
		printf("  Total conditions not taken: %d / %d\n", f->total_conditions-f->total_conditions_covered,f->total_conditions);
        for (int j = 0; j < f->num_branches; j++) {
            const BranchInfo *b = &f->branches[j];
            printf("    Branch %d (line %d block %d): taken=%d\n",
                   b->branch_id, b->line_num, b->block_id, b->taken_count);

            if (b->has_cond_coverage) {
                printf("      Condition outcomes covered: %d/%d\n",
                       b->cond_cov_num, b->cond_cov_den);
            }

            for (int k = 0; k < b->num_conditions; k++) {
                const ConditionInfo *c = &b->conditions[k];
                printf("      Condition %d missing: true=%d false=%d\n",
                       c->cond_id, c->true_missing, c->false_missing);
            }
        }
        printf("\n");
    }
} 

