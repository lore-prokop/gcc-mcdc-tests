/*=========================================================================*//**
 ** \brief Remove leading and trailing whitespace (spaces, tabs, CR, LF) from a
 **        mutable C string in place
 ** \param [in,out] s Pointer to a null-terminated character buffer to be
 **                   trimmed  The buffer contents are modified in place and
 **                   must not be NULL
 ** \details Performs two trimming operations:
 **          1) Leading trim: advances a pointer past leading spaces or tabs and
 **             shifts the remaining characters left using memmove()
 **          2) Trailing trim: walks backward from the end of the string and
 **             replaces trailing whitespace with '\0'
 ** \verbatim
 ** Global_reads_writes Reads: none  Writes: none (operates only on the
 **         caller-provided buffer)** Limitations,Assumptions,Notes:
 **          - Caller must provide a writable, null-terminated buffer
 **          - Behavior undefined if s is NULL
 **          - Only ASCII whitespace is trimmed
 **          - memmove() is used to safely handle overlapping regions
 ** Algorithm:
 **   p = s
 **   Set p to the start of the string
 **   Advance p while it points to a leading space or tab
 **   If p moved forward:
 **       Shift the remaining characters left using memmove()
 **   Compute the current length of the string
 **   While the last character is whitespace:
 **       Replace it with '\0' and reduce the length
 **   Stop when no trailing whitespace remains
 ** History:
 **   03/24/2026  Lore/Copilot  Initial documentation added
 ** \endverbatim
 *//*=========================================================================*/

static void trim(char *s)
{
    char *p = s;
    while (*p == ' ' || *p == '\t')
        p++;

    if (p != s)
        memmove(s, p, strlen(p) + 1);

    size_t len = strlen(s);
    while (len > 0 &&
           (s[len-1] == '\n' || s[len-1] == '\r' ||
            s[len-1] == ' '  || s[len-1] == '\t'))
    {
        s[len-1] = '\0';
        len--;
    }
}

/*=========================================================================*//**
 ** \brief Search the coverage database for a function with the specified name
 **        and return its associated FunctionInfo record
 ** \param [in] db Pointer to a CoverageDB structure containing all parsed
 **                function coverage records  Must not be NULL
 ** \param [in] name Null-terminated string naming the function to locate  Must
 **                  not be NULL
 ** \return Pointer to the matching FunctionInfo record if found  NULL if no
 **         matching function exists in the database
 ** \details Iterates through the function table stored in the CoverageDB
 **          structure and compares each entry's name field to the requested
 **          function name using strcmp()  If a match is found the corresponding
 **          FunctionInfo pointer is returned immediately  If no match is found
 **          after scanning all entries the function returns NULL
 ** \verbatim
 ** Global_reads_writes Reads: none  Writes: none 
 ** Limitations,Assumptions,Notes
 **          - Caller must ensure db and name are valid non-NULL pointers
 **          - Lookup is linear in db->count and may be slow for large datasets
 **          - Name comparison is case-sensitive because strcmp() is used
 ** Algorithm:
 **   Start at the first function entry in the CoverageDB
 **   For each entry in order:
 **       Compare the entry's name to the requested name
 **       If the names match exactly:
 **           Return a pointer to that entry's FunctionInfo record
 **   If no entry matches after scanning the entire list:
 **       Return NULL to indicate the function was not found
 ** History:
 **   03/24/2026  Lore/Copilot  Initial documentation added
 ** \endverbatim
 *//*=========================================================================*/

static FunctionInfo* find_function(const CoverageDB *db, const char *name)
{
    for (int i = 0; i < db->count; i++)
    {
        if (strcmp(db->funcs[i].name, name) == 0)
            return &db->funcs[i];
    }
    return NULL;
}

/*==============================================================================
**                Database Init / Free
**============================================================================*/

/*=========================================================================*//**
 ** \brief Initialize a CoverageDB structure to an empty state and allocate the
 **        initial function table
 ** \param [in,out] db Pointer to a CoverageDB structure to be initialized  Must
 **                   not be NULL
 ** \details Sets the database to an empty state by initializing the function
 **          count to zero and allocating an initial array of FunctionInfo
 **          structures  If memory allocation fails the function prints an error
 **          message and terminates the program
 ** \verbatim
 ** Global_reads_writes 
 **         Reads: none  Writes: db->count  db->cap, db->funcs
 ** Algorithm:
 **   Set the function count to zero
 **   Set the initial capacity to 16 entries
 **   Allocate an array of FunctionInfo structures sized to the capacity
 **   If allocation fails:
 **       Print an error message and exit the program
 ** Limitations,Assumptions,Notes
 **          - Caller must provide a valid CoverageDB pointer
 **          - Initial capacity is fixed at 16 entries
 **          - Function terminates the program on allocation failure
 ** History:
 **   03/24/2026  Lore/Copilot  Initial documentation added
 ** \endverbatim
 *//*=========================================================================*/

static void init_db(CoverageDB *db)
{
    db->count = 0;
    db->cap   = 16;
    db->funcs = calloc(db->cap, sizeof(FunctionInfo));
    if (!db->funcs)
    {
        fprintf(stderr, "Out of memory\n");
        exit(1);
    }
}

/*=========================================================================*//**
 ** \brief Release all dynamically allocated memory associated with a CoverageDB
 **        structure
 ** \param [in,out] db Pointer to a CoverageDB structure whose contents will be
 **                   freed  May be NULL
 ** \details Frees all memory allocated for branches and conditions within each
 **          FunctionInfo record and then frees the function table itself  If db
 **          is NULL the function performs no action
 ** \verbatim
 ** Global_reads_writes Reads: db->count  db->funcs  Writes: none
 ** Limitations,Assumptions,Notes
 **          - Caller must ensure no further use of the database after freeing
 **          - Function does not free the CoverageDB structure itself
 **          - Safe to call with a NULL pointer
 ** Algorithm:
 **   If db is NULL:
 **       Return immediately
 **   For each function in the database:
 **       For each branch in the function:
 **           Free the branch's condition array
 **       Free the branch array for the function
 **   Free the top-level function table
 ** History:
 **   03/24/2026  Lore/Copilot  Initial documentation added
 ** \endverbatim
 *//*=========================================================================*/

static void free_db(CoverageDB *db)
{
    if (!db)
        return;

    for (int i = 0; i < db->count; i++)
    {
        FunctionInfo *f = &db->funcs[i];
        for (int j = 0; j < f->num_branches; j++)
        {
            BranchInfo *b = &f->branches[j];
            free(b->conditions);
        }
        free(f->branches);
    }

    free(db->funcs);
}

/*==============================================================================
**  Dynamic Growth Helpers
**============================================================================*/

/*=========================================================================*//**
 ** \brief Add a new FunctionInfo record to the CoverageDB, expanding storage if
 **        needed, and initialize the new record
 ** \param [in,out] db Pointer to a CoverageDB structure that will receive the
 **                   new function entry  Must not be NULL
 ** \param [in] name Null-terminated string naming the function to add  Must not
 **                  be NULL
 ** \return Pointer to the newly created FunctionInfo record
 ** \details Ensures sufficient capacity for a new FunctionInfo entry by growing
 **          the function table when full  Initializes the new record to zero,
 **          copies the function name, allocates the initial branch array, and
 **          returns a pointer to the new entry
 ** \verbatim
 ** Global_reads_writes Reads: db->count  db->cap  db->funcs
 **         Writes: db->count  db->cap  db->funcs and fields of the new record
 ** Limitations,Assumptions,Notes
 **          - Caller must provide valid db and name pointers
 **          - Capacity grows by doubling when full
 **          - Function terminates the program on allocation failure
 **          - Name is truncated if longer than the destination buffer
 ** Algorithm:
 **   If the function table is full:
 **       Double the capacity
 **       Reallocate the function table to the new size
 **       If reallocation fails:
 **           Print an error and exit
 **   Select the next free FunctionInfo slot and increment the count
 **   Clear the new record with memset
 **   Copy the function name into the record
 **   Allocate the initial branch array with capacity 8
 **   If allocation fails:
 **       Print an error and exit
 **   Return a pointer to the new FunctionInfo record
 ** History
 **   03/24/2026  Lore/Copilot  Initial documentation added
 ** \endverbatim
 *//*=========================================================================*/

static FunctionInfo* add_function(CoverageDB *db, const char *name)
{
    if (db->count == db->cap)
    {
        db->cap *= 2;
        FunctionInfo *tmp =
            realloc(db->funcs, db->cap * sizeof(FunctionInfo));
        if (!tmp)
        {
            fprintf(stderr, "Out of memory (functions)\n");
            exit(1);
        }
        db->funcs = tmp;
    }

    FunctionInfo *f = &db->funcs[db->count++];
    memset(f, 0, sizeof(FunctionInfo));
    strncpy(f->name, name, sizeof(f->name) - 1);

    f->cap_branches = 8;
    f->branches = calloc(f->cap_branches, sizeof(BranchInfo));
    if (!f->branches)
    {
        fprintf(stderr, "Out of memory (branches)\n");
        exit(1);
    }

    return f;
}

/*=========================================================================*//**
 ** \brief Retrieve an existing FunctionInfo record by name or create a new one
 **        if no matching record exists
 ** \param [in,out] db Pointer to a CoverageDB structure to search and possibly
 **                   modify  Must not be NULL
 ** \param [in] name Null-terminated string naming the function to locate  Must
 **                  not be NULL
 ** \return Pointer to the existing or newly created FunctionInfo record
 ** \details Searches the function table for a matching name using strcmp  If a
 **          match is found the corresponding FunctionInfo pointer is returned
 **          If no match is found a new FunctionInfo record is created and
 **          returned
 ** \verbatim
 ** Global_reads_writes Reads: db->count  db->funcs  Writes: db->count
 **         db->cap  db->funcs if a new record is created
 ** Limitations,Assumptions,Notes
 **          - Caller must provide valid db and name pointers
 **          - Name comparison is case-sensitive
 **          - May trigger allocation growth through add_function
 ** Algorithm:
 **   Scan each existing function entry in order
 **   For each entry:
 **       If the entry's name matches the requested name:
 **           Return a pointer to that entry
 **   If no match is found:
 **       Create a new FunctionInfo record using add_function
 **       Return the pointer to the new record
 ** History
 **   03/24/2026  Lore/Copilot  Initial documentation added
 ** \endverbatim
 *//*=========================================================================*/

static FunctionInfo* get_function(CoverageDB *db, const char *name)
{
    for (int i = 0; i < db->count; i++)
    {
        if (strcmp(db->funcs[i].name, name) == 0)
            return &db->funcs[i];
    }

    return add_function(db, name);
}

/*=========================================================================*//**
 ** \brief Add a new BranchInfo record to a FunctionInfo structure, expanding
 **        storage if needed, and initialize the new record
 ** \param [in,out] f Pointer to a FunctionInfo structure that will receive the
 **                   new branch entry  Must not be NULL
 ** \param [in] branch_id Numeric identifier for the branch
 ** \param [in] line_num Numeric identifier for the line containing the branch
 ** \return Pointer to the newly created BranchInfo record
 ** \details Ensures sufficient capacity for a new BranchInfo entry by growing
 **          the branch array when full  Initializes the new record to zero,
 **          assigns the branch and block identifiers, allocates the initial
 **          condition array, and returns a pointer to the new entry
 ** \verbatim
 ** Global_reads_writes Reads: f->num_branches  f->cap_branches
 **         f->branches  Writes: f->num_branches  f->cap_branches  f->branches
 **         and fields of the new record
 ** Limitations,Assumptions,Notes
 **          - Caller must provide a valid FunctionInfo pointer
 **          - Capacity grows by doubling when full
 **          - Function terminates the program on allocation failure
 ** Algorithm:
 **   If the branch array is full:
 **       Double the capacity
 **       Reallocate the branch array to the new size
 **       If reallocation fails:
 **           Print an error and exit
 **   Select the next free BranchInfo slot and increment the count
 **   Clear the new record with memset
 **   Store the branch_id and line_num
 **   Allocate the initial condition array with capacity 4
 **   If allocation fails:
 **       Print an error and exit
 **   Return a pointer to the new BranchInfo record
 ** History
 **   03/24/2026  Lore/Copilot  Initial documentation added
 **   10/20/2026  Lore Prokop   Per git issue #1, changed to Line Number Keying
 **                             rather than block id keying
 ** \endverbatim
 *//*=========================================================================*/

static BranchInfo* add_branch(FunctionInfo *f, int branch_id, int line_num, int block_id)
{
    if (f->num_branches == f->cap_branches)
    {
        f->cap_branches *= 2;
        BranchInfo *tmp =
            realloc(f->branches, f->cap_branches * sizeof(BranchInfo));
        if (!tmp)
        {
            fprintf(stderr, "Out of memory (branches grow)\n");
            exit(1);
        }
        f->branches = tmp;
    }
    BranchInfo *b = &f->branches[f->num_branches++];
    memset(b, 0, sizeof(BranchInfo));
    b->branch_id = branch_id;
    b->block_id  = block_id;
	b->line_num = line_num;
    b->cap_conditions = 4;
    b->conditions = calloc(b->cap_conditions, sizeof(ConditionInfo));
    if (!b->conditions)
    {
        fprintf(stderr, "Out of memory (conditions)\n");
        exit(1);
    }
    return b;
}

/*=========================================================================*//**
 ** \brief Add a new ConditionInfo record to a BranchInfo structure, expanding
 **        storage if needed, and initialize the new record
 ** \param [in,out] b Pointer to a BranchInfo structure that will receive the
 **                   new condition entry  Must not be NULL
 ** \param [in] cond_id Numeric identifier for the condition
 ** \return Pointer to the newly created ConditionInfo record
 ** \details Ensures sufficient capacity for a new ConditionInfo entry by
 **          growing the condition array when full  Initializes the new record
 **          to zero, assigns the condition identifier, and returns a pointer to
 **          the new entry
 ** \verbatim
 ** Global_reads_writes Reads: b->num_conditions  b->cap_conditions
 **         b->conditions  Writes: b->num_conditions  b->cap_conditions
 **         b->conditions and fields of the new record
 ** Limitations,Assumptions,Notes
 **          - Caller must provide a valid BranchInfo pointer
 **          - Capacity grows by doubling when full
 **          - Function terminates the program on allocation failure
 ** Algorithm:
 **   If the condition array is full:
 **       Double the capacity
 **       Reallocate the condition array to the new size
 **       If reallocation fails:
 **           Print an error and exit
 **   Select the next free ConditionInfo slot and increment the count
 **   Clear the new record with memset
 **   Store the cond_id value
 **   Return a pointer to the new ConditionInfo record
 ** History
 **   03/24/2026  Lore/Copilot  Initial documentation added
 ** \endverbatim
 *//*=========================================================================*/

static ConditionInfo* add_condition(BranchInfo *b, int cond_id)
{
    if (b->num_conditions == b->cap_conditions)
    {
        b->cap_conditions *= 2;
        ConditionInfo *tmp =
            realloc(b->conditions,
                    b->cap_conditions * sizeof(ConditionInfo));
        if (!tmp)
        {
            fprintf(stderr, "Out of memory (conditions grow)\n");
            exit(1);
        }
        b->conditions = tmp;
    }

    ConditionInfo *c = &b->conditions[b->num_conditions++];
    memset(c, 0, sizeof(ConditionInfo));
    c->cond_id = cond_id;

    return c;
}

