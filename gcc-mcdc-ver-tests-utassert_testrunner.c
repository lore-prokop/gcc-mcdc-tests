/*=========================================================================*//**
 ** \brief Query the number of condition outcomes covered for a specific branch
 **        identified by function name, line num, and branch ID
 ** \param [in] db Pointer to the CoverageDB structure to search  Must not be
 **                NULL
 ** \param [in] func_name Null-terminated string naming the function to inspect
 **                       Must not be NULL
 ** \param [in] line_num Numeric identifier of the line containing the branch
 ** \param [in] branch_id Numeric identifier of the branch within the block
 ** \return Number of covered condition outcomes if available  Returns 0 if the
 **         branch has no condition coverage  Returns -1 if the function or
 **         branch cannot be found
 ** \details Searches for the specified function and branch and returns the
 **          number of condition outcomes covered  If the branch does not
 **          include condition coverage information the function returns zero
 ** \verbatim
 ** Global_reads_writes Reads: db->funcs and nested branch fields
 **         Writes: none
 ** Limitations,Assumptions,Notes
 **          - Caller must provide valid db and func_name pointers
 **          - Name comparison is case-sensitive
 **          - Returns -1 when the function or branch is not found
 ** Algorithm:
 **   Search the function table for a name match
 **   If no matching function is found:
 **       Return -1
 **   Search the function's branches for a matching line_num and branch_id
 **   If no matching branch is found:
 **       Return -1
 **   If the branch has no condition coverage:
 **       Return 0
 **   Otherwise return the recorded number of covered conditions
 ** History
 **   03/24/2026 	Lore/Copilot  Initial code and documentation complete
 **   10/20/2026  Lore Prokop   Per git issue #1, changed to Line Number Keying
 **                             rather than block id keying
 ** \endverbatim
 *//*=========================================================================*/
 
 int query_conditions_taken(const CoverageDB *db,
                           const char *func_name,
                           int line_num,
                           int branch_id)
{
    /* Find function */
    FunctionInfo *f = NULL;
    for (int i = 0; i < db->count; i++) {
        if (strcmp(db->funcs[i].name, func_name) == 0) {
            f = &db->funcs[i];
            break;
        }
    }
    if (!f)
        return -1;   /* function not found */

    /* Search all branches for matching block_id + branch_id */
    BranchInfo *br = NULL;
    for (int i = 0; i < f->num_branches; i++) {
        BranchInfo *candidate = &f->branches[i];

        if (candidate->line_num == line_num &&
            candidate->branch_id == branch_id)
        {
            br = candidate;
            break;
        }
    }
    if (!br)
        return -1;   /* no matching block+branch pair */

    /* If no condition coverage exists, return 0 */
    if (!br->has_cond_coverage)
        return 0;

    /* Otherwise return the number of conditions covered */
    return br->cond_cov_num;
}

/*=========================================================================*//**
 ** \brief Query whether a specific branch was taken by matching function name,
 **        block ID, and branch ID
 ** \param [in] db Pointer to the CoverageDB structure to search  Must not be
 **                NULL
 ** \param [in] func_name Null-terminated string naming the function to inspect
 **                       Must not be NULL
 ** \param [in] line_num Numeric identifier of the line containing the branch
 ** \param [in] branch_id Numeric identifier of the branch within the block
 ** \return The branch's taken count if found  Returns -1 if the function or
 **         branch cannot be located
 ** \details Locates the specified function and searches its branches for a
 **          matching block and branch identifier  If found the branch's taken
 **          count is returned  If the function or branch does not exist the
 **          function returns -1
 ** \verbatim
 ** Global_reads_writes Reads: db->funcs and nested branch fields
 **         Writes: none
 ** Limitations,Assumptions,Notes
 **          - Caller must provide valid db and func_name pointers
 **          - Name comparison is case-sensitive
 **          - Returns -1 when the function or branch is not found
 ** Algorithm:
 **   Locate the function by name using find_function
 **   If no matching function is found:
 **       Return -1
 **   Validate that branch_id is within the function's branch range
 **   Search all branches for a matching block_id and branch_id pair
 **   If no matching branch is found:
 **       Return -1
 **   Return the branch's taken_count value
 ** History
 **   03/24/2026  Lore/Copilot  Initial code and documentation complete
 **   10/20/2026  Lore Prokop   Per git issue #1, changed to Line Number Keying
 **                             rather than block id keying
 ** \endverbatim
 *//*=========================================================================*/

 int query_branch_taken(const CoverageDB *db,
                       const char *func_name,
                       int line_num,
                       int branch_id)
{
    FunctionInfo *f = find_function(db, func_name);
    if (!f)
        return -1;   /* function not found */

    if (branch_id < 0 || branch_id >= f->num_branches)
        return -1;   /* invalid branch */

    /* Search all branches for matching block_id + branch_id */
    BranchInfo *br = NULL;
    for (int i = 0; i < f->num_branches; i++) {
        BranchInfo *candidate = &f->branches[i];

        if (candidate->line_num == line_num &&
            candidate->branch_id == branch_id)
        {
            br = candidate;
            break;
        }
    }
    if (!br)
        return -1;   /* no matching block+branch pair */
    return (br->taken_count);
}

/*=========================================================================*//**
 ** \brief Query whether a specific condition outcome (true or false) is missing
 **        for a given function, block, branch, and condition identifier
 ** \param [in] db Pointer to the CoverageDB structure to search  Must not be
 **                NULL
 ** \param [in] func_name Null-terminated string naming the function to inspect
 **                       Must not be NULL
 ** \param [in] line_num Numeric identifier of the line containing the branch
 ** \param [in] branch_id Numeric identifier of the branch within the block
 ** \param [in] cond_id Numeric identifier of the condition within the branch
 ** \param [in] Boolean_value 1 to query the true outcome, 0 to query the false
 **                           outcome
 ** \return 1 if the requested outcome is missing  0 if it is covered  -1 if the
 **         function, branch, or condition cannot be found
 ** \details Locates the specified function, branch, and condition and returns
 **          whether the requested Boolean outcome is marked as missing  If any
 **          component cannot be found the function returns -1
 ** \verbatim
 ** Global_reads_writes Reads: db->funcs and nested branch/condition
 **         fields  Writes: none
 ** Limitations,Assumptions,Notes
 **          - Caller must provide valid db and func_name pointers
 **          - Name comparison is case-sensitive
 **          - Returns -1 when the function, branch, or condition is not found
 ** Algorithm:
 **   Locate the function by name
 **   If not found:
 **       Return -1
 **   Validate that branch_id is within range
 **   Search all branches for a matching block_id and branch_id pair
 **   If no matching branch is found:
 **       Return -1
 **   Search the branch's conditions for a matching cond_id
 **   If no matching condition is found:
 **       Return -1
 **   If Boolean_value is true:
 **       Return 1 if true_missing is set, otherwise 0
 **   Else:
 **       Return 1 if false_missing is set, otherwise 0
 ** History
 **   03/24/2026  Lore/Copilot  Initial code and documentation complete
 **   10/20/2026  Lore Prokop   Per git issue #1, changed to Line Number Keying
 **                             rather than block id keying
 ** \endverbatim
 *//*=========================================================================*/

 int query_missing_condition(const CoverageDB *db,   
                            const char *func_name,
                            int line_num,
                            int branch_id,
                            int cond_id,
                            int Boolean_value)
{
    FunctionInfo *f = find_function(db, func_name);
    if (!f)
        return -1;   /* function not found */

    if (branch_id < 0 || branch_id >= f->num_branches)
        return -1;   /* invalid branch */

    /* Search all branches for matching block_id + branch_id */
    BranchInfo *br = NULL;
    for (int i = 0; i < f->num_branches; i++) {
        BranchInfo *candidate = &f->branches[i];

        if (candidate->line_num == line_num &&
            candidate->branch_id == branch_id)
        {
            br = candidate;
            break;
        }
    }
    if (!br)
        return -1;   /* no matching block+branch pair */
	
    /* Find condition */
    ConditionInfo *ci = NULL;
    for (int i = 0; i < br->num_conditions; i++) {
        if (br->conditions[i].cond_id == cond_id) {
            ci = &br->conditions[i];
            break;
        }
    }
    if (!ci)
        return -1;   /* condition not found */

    /* Return true of the coverage for that Boolean value is missing */
    if (Boolean_value)
        return ci->true_missing ? 1 : 0;
    else
        return ci->false_missing ? 1 : 0;
}

/*=========================================================================*//**
 ** \brief Query a specific coverage statistic for a function based on the
 **        requested QueryType value
 ** \param [in] db Pointer to the CoverageDB structure to search  Must not be
 **                NULL
 ** \param [in] func_name Null-terminated string naming the function to inspect
 **                       Must not be NULL
 ** \param [in] type Enumeration selecting which statistic to return
 ** \return The requested statistic value  Returns -1 if the function cannot be
 **         found or if the query type is invalid
 ** \details Locates the specified function and returns the coverage statistic
 **          associated with the provided QueryType  Statistics include uncovered
 **          lines, branches not taken, missing conditions, calls not taken,
 **          total lines, total blocks, and blocks not taken
 ** \verbatim
 ** Global_reads_writes Reads: db->funcs and nested fields  Writes: none
 ** Limitations,Assumptions,Notes
 **          - Caller must provide valid db and func_name pointers
 **          - Name comparison is case-sensitive
 **          - Returns -1 for unknown query types or missing functions
 ** Algorithm:
 **   Locate the function by name
 **   If not found:
 **       Return -1
 **   Switch on the requested QueryType:
 **       Return the corresponding statistic from the FunctionInfo record
 **       If the type is not recognized:
 **           Return -1
 ** History
 **   03/24/2026   Lore/Copilot  Initial code and documentation complete
 ** \endverbatim
 *//*=========================================================================*/
 
 int query_function_stats(const CoverageDB *db,
                         const char *func_name,
                         QueryType type)
{
    FunctionInfo *f = find_function(db, func_name);
    if (!f)
        return -1;   /* function not found */

    switch (type) {
        case LINES_NOT_COVERED:
            return f->uncovered_lines;
        case BRANCHES_NOT_COVERED: {
            /* compute branches not taken on the fly */
            return f->branches_taken_zero;
        }
        case CONDITIONS_NOT_COVERED: {
            int missing = f->total_conditions - f->total_conditions_covered;
            return missing;
        }
		case CALLS_NOT_TAKEN:
			return f->calls_not_taken;
			
		case TOTAL_LINES:
			return f->total_lines;
			
		case BLOCKS_TOTAL:
			return f->total_blocks;

		case BLOCKS_NOT_TAKEN:
			return f->blocks_not_taken;

        default:
            return -1;
    }
}

